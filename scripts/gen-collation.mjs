// Derives the documented name-collation rule from ICU (node's Intl.Collator, locale en-US, the default
// of String.prototype.localeCompare) and writes it as data both ports read:
//   data/collation.json          { "from": 32, "to": 383, "weights": [[p,s,t] ...] }  (Python, TS test)
//   goose/collation_table.goose  the same table as a Goose constant
// Rule: a name becomes code points; each code point in [from, to] has weights (primary, secondary,
// tertiary); names compare by the primary sequence, then the secondary, then the tertiary (shorter
// prefix first). Code points outside the table, and the few in the table that ICU expands
// (see UNSUPPORTED), sort after every table character by code point. Names must be NFC.
// Run: node scripts/gen-collation.mjs   (also self-checks the rule against localeCompare)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FROM = 0x20, TO = 0x17f;
// ICU expands these to several letters (ss, ae, oe, ij, 'n) or makes them contractions: no single weight.
const UNSUPPORTED = new Set([0xdf, 0xc6, 0xe6, 0x132, 0x133, 0x152, 0x153, 0x149, 0x17f, 0xa0, 0xad, 0xb2, 0xb3, 0xb9, 0xbc, 0xbd, 0xbe]);
const full = new Intl.Collator("en-US");
const base = new Intl.Collator("en-US", { sensitivity: "base" });
const accent = new Intl.Collator("en-US", { sensitivity: "accent" });

const cps = [];
for (let c = FROM; c <= TO; c++) {
  if (c >= 0x7f && c <= 0x9f) continue;
  if (UNSUPPORTED.has(c)) continue;
  cps.push(c);
}
const ch = (c) => String.fromCodePoint(c);
cps.sort((a, b) => full.compare(ch(a), ch(b)) || a - b);

const weights = new Map();
let p = 0, s = 0, t = 0, prev = null;
for (const c of cps) {
  if (prev === null) { p = 1; s = 0; t = 0; }
  else if (base.compare(ch(prev), ch(c)) !== 0) { p++; s = 0; t = 0; }
  else if (accent.compare(ch(prev), ch(c)) !== 0) { s++; t = 0; }
  else t++;
  weights.set(c, [p, s, t]);
  prev = c;
}
const arr = [];
for (let c = FROM; c <= TO; c++) arr.push(weights.get(c) ?? [0, 0, 0]);
const maxS = Math.max(...arr.map((w) => w[1])), maxT = Math.max(...arr.map((w) => w[2]));
if (maxS > 255 || maxT > 255 || p > 0xffff) throw new Error("weights too large for the key encoding");

writeFileSync(join(root, "data/collation.json"), JSON.stringify({ from: FROM, to: TO, weights: arr }) + "\n");
const flat = arr.flat();
let g = "// GENERATED by scripts/gen-collation.mjs. Do not edit. Weights (primary, secondary, tertiary) for code points\n";
g += `// ${FROM}..${TO}; a primary of 0 means "not in the table".\n`;
g += `let COLL_FROM: i64 = ${FROM};\nlet COLL_TO: i64 = ${TO};\nlet COLL: i32[] = [\n`;
for (let i = 0; i < flat.length; i += 24) g += "    " + flat.slice(i, i + 24).join(", ") + ",\n";
g += "];\n";
writeFileSync(join(root, "goose/collation_table.goose"), g);

// Self-check of the rule against ICU on random Latin strings (exported for the tests as well).
export function ruleKey(name) {
  const P = [], S = [], T = [];
  for (const c of name) {
    const cp = c.codePointAt(0);
    const w = cp >= FROM && cp <= TO ? arr[cp - FROM] : [0, 0, 0];
    if (w[0] === 0) { P.push(0x10000 + cp); S.push(0); T.push(0); } else { P.push(w[0]); S.push(w[1]); T.push(w[2]); }
  }
  return [P, S, T];
}
function cmpSeq(a, b) {
  for (let i = 0; i < Math.min(a.length, b.length); i++) if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  return a.length === b.length ? 0 : a.length < b.length ? -1 : 1;
}
export const ruleCompare = (x, y) => {
  const a = ruleKey(x), b = ruleKey(y);
  return cmpSeq(a[0], b[0]) || cmpSeq(a[1], b[1]) || cmpSeq(a[2], b[2]);
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pool = cps.filter((c) => c < 0x180);
  let seed = 7;
  const rnd = (k) => ((seed = (Math.imul(seed, 1103515245) + 12345) >>> 0), (seed >>> 8) % k);
  let bad = 0, n = 200000;
  const mk = () => { let r = ""; const L = 1 + rnd(6); for (let i = 0; i < L; i++) r += ch(pool[rnd(pool.length)]); return r; };
  for (let i = 0; i < n; i++) {
    const a = mk(), b = mk();
    if (Math.sign(a.localeCompare(b)) !== ruleCompare(a, b)) { if (bad++ < 5) console.error("MISMATCH", JSON.stringify([a, b]), a.localeCompare(b), ruleCompare(a, b)); }
  }
  console.log(`table ${arr.length} entries, ${p} primaries; self-check vs localeCompare: ${n - bad}/${n} agree`);
  process.exit(bad ? 1 : 0);
}
